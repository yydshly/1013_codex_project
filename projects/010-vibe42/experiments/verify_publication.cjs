"use strict";
// Verify the actual HTTP(S) publication, its complete summaries and downloads.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const {chromium} = require("playwright");
const project = path.resolve(__dirname, "..");
const target = new URL(process.argv[2] || "http://127.0.0.1:8786/010-vibe42/");
assert.ok(["http:", "https:"].includes(target.protocol));
const output = process.argv[3] || "publication-browser-local.json";
assert.equal(path.basename(output), output);
const metadata = JSON.parse(fs.readFileSync(path.join(project,"project.json"),"utf8"));
const labels = ["能力","本质","原理","价值","使用场景","可扩展场景"];
const expected = labels.map(label => metadata.summary_sections.find(item => item.label === label));
const checks = [], errors = [];
(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => {if(message.type()==="error") errors.push(message.text());});
    page.on("requestfailed", request => errors.push(request.url()+": "+request.failure().errorText));
    const response = await page.goto(target.href,{waitUntil:"networkidle"});
    assert.equal(response.status(),200);
    const digest = await page.locator(".understanding-thesis > div").evaluateAll(nodes => nodes.map(node => ({label:node.querySelector("dt").textContent,text:node.querySelector("dd").textContent})));
    assert.deepEqual(digest,expected);
    assert.equal(await page.locator(".reading-content .research-section").count(),16);
    checks.push({name:"六项完整摘要与16个正文入口",status:"passed"});
    await page.locator('[data-map-view="principle"]').click();
    await page.locator('[data-principle="agent"]').click();
    assert.equal(await page.locator("#principle-title").innerText(),"Agent 与工具");
    await page.locator('[data-principle-trace="output"]').click();
    for(let i=1;i<5;i++) await page.locator("#principle-next").click();
    assert.equal(await page.locator("#principle-next").isDisabled(),true);
    await page.locator('[data-map-route="relay"]').click();
    assert.match(await page.locator("#map-route-note").innerText(),/没有抓包/);
    checks.push({name:"原理节点、结果回传和中继交互",status:"passed"});
    const downloadPromise = page.waitForEvent("download");
    await page.locator('.map-toolbar a[download$=".png"]').click();
    const download = await downloadPromise;
    const bytes = fs.readFileSync(await download.path());
    assert.equal(bytes.subarray(1,4).toString(),"PNG");
    checks.push({name:"公开PNG实际下载",filename:download.suggestedFilename(),status:"passed"});
    await page.setViewportSize({width:390,height:844});
    await page.reload({waitUntil:"networkidle"});
    const width = await page.evaluate(() => ({viewport:innerWidth,document:document.documentElement.scrollWidth}));
    assert.equal(width.document,width.viewport);
    assert.deepEqual(await page.locator(".understanding-thesis dt").allTextContents(),labels);
    checks.push({name:"390px完整摘要和布局",width,status:"passed"});
    await page.goto(new URL("../",target).href,{waitUntil:"networkidle"});
    const row = page.locator("tr").filter({has:page.locator('a[href="./010-vibe42/"]')});
    assert.equal(await row.count(),1);
    const rootDigest = await row.locator(".summary-sections > div").evaluateAll(nodes => nodes.map(node => ({label:node.querySelector("dt").textContent,text:node.querySelector("dd").textContent})));
    assert.deepEqual(rootDigest,metadata.summary_sections);
    await row.locator('a.primary[href="./010-vibe42/"]').click();
    await page.waitForLoadState("networkidle");
    assert.equal(new URL(page.url()).pathname,target.pathname);
    checks.push({name:"统一索引17项完整摘要和进入研究页",status:"passed"});
    const noJs = await browser.newContext({javaScriptEnabled:false});
    const plain = await noJs.newPage();
    await plain.goto(target.href,{waitUntil:"networkidle"});
    assert.equal(await plain.locator(".understanding-thesis dt").count(),6);
    assert.equal(await plain.locator(".source-list li").count(),21);
    checks.push({name:"关闭JavaScript后摘要与来源可读",status:"passed"});
    await noJs.close();
    assert.deepEqual(errors,[]);
    const report = {checked_at:new Date().toISOString(),url:target.href,browser:`Chromium ${browser.version()}`,scope:"已访问的静态研究网页；不验证真实Vibe42产品",checks,errors};
    fs.writeFileSync(path.join(__dirname,"results",output),JSON.stringify(report,null,2)+"\n");
    console.log(JSON.stringify({url:target.href,checks:checks.length,errors:errors.length,report:output},null,2));
  } finally {await browser.close();}
})().catch(error => {console.error(error);process.exitCode=1;});
